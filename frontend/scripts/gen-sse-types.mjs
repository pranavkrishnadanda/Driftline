#!/usr/bin/env node
// Generates src/lib/sse/events.ts from the SSE contract's JSON Schema.
//
//   npm run gen:sse                          # reads ../contracts/sse/ask-events.v1.json
//   npm run gen:sse -- path/to/contract.json # or any other copy of the contract
//   DRIFTLINE_SSE_CONTRACT=... npm run gen:sse
//
// The contract file wraps the schema (`{ name, version, framing, examples, schema }`);
// only `schema` is compiled. Re-run whenever the backend regenerates the contract.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = resolve(
  process.argv[2] ?? process.env.DRIFTLINE_SSE_CONTRACT ?? resolve(root, "../contracts/sse/ask-events.v1.json"),
);
const output = resolve(root, "src/lib/sse/events.ts");

let raw;
try {
  raw = await readFile(input, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  console.error(`gen:sse: ${input} not found. Pass the contract path: npm run gen:sse -- <file>`);
  process.exit(1);
}
const contract = JSON.parse(raw);
if (!contract.schema) {
  throw new Error(`${input} has no "schema" key; is it an SSE contract file?`);
}

// Two wire-faithful adjustments before compiling:
// - Pydantic always serialises the `type` discriminator, so make it required; otherwise
//   `type?: "token"` would stop TypeScript narrowing the union on `event.type`.
// - Drop per-property `title`s (Pydantic adds one to every field), which would otherwise
//   become dozens of alias types (`Type1`, `Idx1`, ...). Model titles stay.
const schema = structuredClone(contract.schema);
for (const def of Object.values(schema.$defs ?? {})) {
  for (const prop of Object.values(def.properties ?? {})) delete prop.title;
  if (def.properties?.type?.const !== undefined) {
    def.required = [...new Set([...(def.required ?? []), "type"])];
  }
}

const banner = `// GENERATED by \`npm run gen:sse\` from contracts/sse/ask-events.v1.json
// (${contract.name} v${contract.version}). Do not edit by hand; re-run the script.`;

const generated = await compile({ ...schema, title: "AskEvent" }, "AskEvent", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { printWidth: 100 },
});

const footer = `
/** The SSE \`event:\` field values of the ask stream. */
export type AskEventType = AskEvent["type"];

/**
 * Drift-alert events. PLACEHOLDER: \`contracts/sse/alert-events.v1.json\` does not exist
 * yet (it arrives with P4). When it does, extend this script to compile it and replace
 * this union with the generated types.
 */
export type AlertEvent = never;

/** Every event the frontend's SSE streams can deliver. */
export type DriftlineEvent = AskEvent | AlertEvent;
`;

await writeFile(output, `${generated.trimEnd()}\n${footer}`);
console.log(`wrote ${relative(root, output)} from ${input}`);
