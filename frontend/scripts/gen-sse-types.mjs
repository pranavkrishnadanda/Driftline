#!/usr/bin/env node
// Generates src/lib/sse/events.ts from the SSE contracts' JSON Schemas.
//
//   npm run gen:sse                          # reads ../contracts/sse/{ask,alert}-events.v1.json
//   npm run gen:sse -- ask.json alert.json   # or any other copies of the contracts
//   DRIFTLINE_SSE_CONTRACT=... DRIFTLINE_SSE_ALERT_CONTRACT=... npm run gen:sse
//
// Each contract file wraps its schema (`{ name, version, framing, examples, schema }`);
// only `schema` is compiled. Both schemas are merged into one document so the event
// models they share (`ErrorEvent`) are emitted once; a shared model must be identical
// in both. Re-run whenever the backend regenerates a contract.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";

import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const askInput = resolve(
  process.argv[2] ??
    process.env.DRIFTLINE_SSE_CONTRACT ??
    resolve(root, "../contracts/sse/ask-events.v1.json"),
);
const alertInput = resolve(
  process.argv[3] ??
    process.env.DRIFTLINE_SSE_ALERT_CONTRACT ??
    resolve(root, "../contracts/sse/alert-events.v1.json"),
);
const output = resolve(root, "src/lib/sse/events.ts");

async function loadContract(input) {
  let raw;
  try {
    raw = await readFile(input, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    console.error(
      `gen:sse: ${input} not found. Pass the contract paths: npm run gen:sse -- <ask.json> <alert.json>`,
    );
    process.exit(1);
  }
  const contract = JSON.parse(raw);
  if (!contract.schema) {
    throw new Error(`${input} has no "schema" key; is it an SSE contract file?`);
  }
  return contract;
}

const ask = await loadContract(askInput);
const alert = await loadContract(alertInput);

// Merge both $defs. A model both streams use must be the same model on the wire.
const defs = structuredClone(ask.schema.$defs ?? {});
for (const [name, def] of Object.entries(alert.schema.$defs ?? {})) {
  if (name in defs && !isDeepStrictEqual(defs[name], def)) {
    throw new Error(`gen:sse: $defs.${name} differs between ${askInput} and ${alertInput}`);
  }
  defs[name] = structuredClone(def);
}
for (const name of ["AskEvent", "AlertStreamEvent", "DriftlineEvent"]) {
  if (name in defs) throw new Error(`gen:sse: $defs.${name} would shadow a generated union`);
}

// Two wire-faithful adjustments before compiling:
// - Pydantic always serialises the `type` discriminator, so make it required; otherwise
//   `type?: "token"` would stop TypeScript narrowing the union on `event.type`.
// - Drop per-property `title`s (Pydantic adds one to every field), which would otherwise
//   become dozens of alias types (`Type1`, `Idx1`, ...). Model titles stay.
for (const def of Object.values(defs)) {
  for (const prop of Object.values(def.properties ?? {})) delete prop.title;
  if (def.properties?.type?.const !== undefined) {
    def.required = [...new Set([...(def.required ?? []), "type"])];
  }
}

// Each stream's root union becomes a named type; DriftlineEvent is their union.
defs.AskEvent = { title: "AskEvent", oneOf: ask.schema.oneOf };
defs.AlertStreamEvent = { title: "AlertStreamEvent", oneOf: alert.schema.oneOf };
const schema = {
  title: "DriftlineEvent",
  description: "Every event the frontend's SSE streams can deliver.",
  $defs: defs,
  oneOf: [{ $ref: "#/$defs/AskEvent" }, { $ref: "#/$defs/AlertStreamEvent" }],
};

const banner = `// GENERATED by \`npm run gen:sse\` from contracts/sse/ask-events.v1.json
// (${ask.name} v${ask.version}) and contracts/sse/alert-events.v1.json
// (${alert.name} v${alert.version}). Do not edit by hand; re-run the script.`;

const generated = await compile(schema, "DriftlineEvent", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { printWidth: 100 },
});

const footer = `
/** The SSE \`event:\` field values of the ask stream. */
export type AskEventType = AskEvent["type"];

/** The SSE \`event:\` field values of the drift-alert stream. */
export type AlertStreamEventType = AlertStreamEvent["type"];
`;

await writeFile(output, `${generated.trimEnd()}\n${footer}`);
console.log(`wrote ${relative(root, output)} from ${askInput} and ${alertInput}`);
